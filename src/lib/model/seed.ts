function exampleLocations(): LocationMap {
  const unit: StorageLocation = {
    id: "loc_example_unit",
    parentId: null,
    mapObjectId: "obj_example_cabinet",
    kind: "unit",
    label: "Example drawer cabinet",
    code: "EX-01",
    sortOrder: 0,
    diagramPosition: null,
    archived: false,
    compartments: { type: "cabinet", rows: 4, cols: 1 },
    example: true,
  };
  const out: LocationMap = { [unit.id]: unit };
  ["a", "b", "c", "d"].forEach((letter, i) => {
    const id = `loc_example_drawer_${letter}`;
    out[id] = {
      id,
      parentId: unit.id,
      mapObjectId: null,
      kind: "drawer",
      label: `Drawer ${letter.toUpperCase()}`,
      code: `EX-01.${letter.toUpperCase()}`,
      sortOrder: i,
      diagramPosition: { row: i, col: 0 },
      archived: false,
      compartments: letter === "d" ? { type: "binGrid", rows: 2, cols: 3 } : null,
      example: true,
    };
  });
  for (let i = 0; i < 6; i++) {
    const n = String(i + 1).padStart(2, "0");
    const id = `loc_example_d_bin${n}`;
    out[id] = {
      id,
      parentId: "loc_example_drawer_d",
      mapObjectId: null,
      kind: "bin",
      label: `Bin ${n}`,
      code: `EX-01.D.${n}`,
      sortOrder: i,
      diagramPosition: { row: Math.floor(i / 3), col: i % 3 },
      archived: false,
      compartments: null,
      example: true,
    };
  }
  return out;
}

export function createSeedDocument(): ShopDocument {
  const objects: Record<string, MapObject> = {};
  for (const obj of OBJECTS) objects[obj.id] = structuredClone(obj);
  const layout: Layout = {
    id: SEED_LAYOUT_ID,
    name: "Draft — not measured",
    schemaVersion: SCHEMA_VERSION,
    revision: 0,
    coordinateUnits: "arbitrary",
    width: 1200,
    height: 1800,
    verificationStatus: "draft",
    objects,
    updatedAt: null,
    updatedBy: null,
  };
  return { layout, locations: exampleLocations() };
}
